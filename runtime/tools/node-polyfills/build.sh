#!/bin/sh
# Rebuilds runtime/lib/renderer/node-polyfills.js from the pinned packages in
# package.json. Needs npm and network access; the output is committed.
set -eu
DIR=$(cd "$(dirname "$0")" && pwd)
OUT="$DIR/../../lib/renderer/node-polyfills.js"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
cp "$DIR/package.json" "$DIR/entry.js" "$DIR/process-shim.js" "$WORK/"
(cd "$WORK" && npm install --silent --no-audit --no-fund --ignore-scripts >/dev/null)
# Every `require('process')` (readable-stream asks for 'process/') is the page's.
mkdir -p "$WORK/node_modules/process"
for file in index.js browser.js; do cp "$WORK/process-shim.js" "$WORK/node_modules/process/$file"; done
printf '{"name":"process","version":"0.0.0-aurora","main":"index.js","browser":"browser.js"}\n' > "$WORK/node_modules/process/package.json"
# esbuild's own binary comes from its platform package.
(cd "$WORK" && node node_modules/esbuild/install.js >/dev/null 2>&1 || true)
"$WORK/node_modules/.bin/esbuild" "$WORK/entry.js" --bundle --format=iife \
  --global-name=auroraNodeModules --platform=browser --target=safari16 \
  --define:global=globalThis --define:process=__auroraProcess --minify --legal-comments=none --log-level=warning \
  --outfile="$WORK/bundle.js"
VERSIONS=$(cd "$WORK" && node -e '
  const deps = require("./package.json").dependencies;
  console.log(Object.keys(deps).map((name) => `${name} ${require(`./node_modules/${name}/package.json`).version}`).join(", "));')
{
  echo "'use strict';"
  echo ''
  echo '// Generated by runtime/tools/node-polyfills/build.sh; do not edit.'
  echo "// $VERSIONS"
  echo '// (MIT licences; see each package on npm.) The bridge injects this'
  echo "// function's source into pages with nodeIntegration and calls it with the"
  echo "// page's process object."
  echo 'module.exports = function auroraNodePolyfills(__auroraProcess) {'
  cat "$WORK/bundle.js"
  echo 'return auroraNodeModules;'
  echo '};'
} > "$OUT"
wc -c "$OUT"
